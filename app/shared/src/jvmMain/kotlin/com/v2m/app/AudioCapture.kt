package com.v2m.app

/** Платформенно-нейтральный контракт захвата микрофона (Р14, билд #43:
 *  замена javax.sound). Реализация в desktopApp — NativeCapture (ALSA через
 *  JNI); Android получит свою (у него иной бэкенд захвата). Результат всегда
 *  моно PCM на частоте, согласованной open() с устройством: реализация
 *  гарантирует параметры модели, ресемплинг — на её стороне. */
interface AudioCapture {

    /** Результат записи: моно PCM −1..1 на частоте sr. */
    data class Result(val pcm: FloatArray, val sr: Int)

    /** Открыть устройство по умолчанию. null — готово, иначе текст причины. */
    fun open(): String?

    /** Остановить захват — безопасно из любого потока. */
    fun stop()

    /** Блокирующий захват до stop() или maxMs; вызывать в фоновом потоке.
     *  null — данных не было (стоп до первого блока). */
    fun record(maxMs: Long = 60_000L): Result?
}
